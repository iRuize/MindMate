-- 用户明确填写的个人偏好，一名用户最多一行。
CREATE TABLE "MINDMATE"."DECISION_PREFERENCE"
(
    "USER_ID"        BIGINT                              NOT NULL,
    "PERSONALITY" CLOB,
    "INTERESTS" CLOB,
    "VALUES" CLOB,
    "GOALS" CLOB,
    "DECISION_STYLE" CLOB,
    "MEMORY_ENABLED" TINYINT   DEFAULT 0                 NOT NULL,
    "CREATED_AT"     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UPDATED_AT"     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    NOT CLUSTER PRIMARY KEY ("USER_ID"),
    CONSTRAINT "CK_DEC_PREF_MEMORY" CHECK ("MEMORY_ENABLED" IN (0, 1))
) STORAGE(ON "MAIN", CLUSTERBTR);

COMMENT ON TABLE "MINDMATE"."DECISION_PREFERENCE" IS '用户明确填写的决策偏好，不从对话隐式提取';
COMMENT ON COLUMN "MINDMATE"."DECISION_PREFERENCE"."USER_ID" IS '归属用户ID，用户一行，主键同时作为owner索引';
COMMENT ON COLUMN "MINDMATE"."DECISION_PREFERENCE"."PERSONALITY" IS '用户自述人格偏好，应用限制1000字符';
COMMENT ON COLUMN "MINDMATE"."DECISION_PREFERENCE"."INTERESTS" IS '用户明确填写的兴趣，应用限制1000字符';
COMMENT ON COLUMN "MINDMATE"."DECISION_PREFERENCE"."VALUES" IS '用户明确填写的价值观，应用限制1000字符';
COMMENT ON COLUMN "MINDMATE"."DECISION_PREFERENCE"."GOALS" IS '用户明确填写的目标，应用限制1000字符';
COMMENT ON COLUMN "MINDMATE"."DECISION_PREFERENCE"."DECISION_STYLE" IS '用户明确填写的决策风格，应用限制1000字符';
COMMENT ON COLUMN "MINDMATE"."DECISION_PREFERENCE"."MEMORY_ENABLED" IS '是否向模型注入偏好：0关闭 1启用，默认关闭';
COMMENT ON COLUMN "MINDMATE"."DECISION_PREFERENCE"."CREATED_AT" IS '创建时间';
COMMENT ON COLUMN "MINDMATE"."DECISION_PREFERENCE"."UPDATED_AT" IS '更新时间';

CREATE TABLE "MINDMATE"."DECISION_SESSION"
(
    "ID"         BIGINT IDENTITY(1, 1) NOT NULL,
    "USER_ID"    BIGINT                              NOT NULL,
    "TITLE"      VARCHAR(400)                        NOT NULL,
    "CREATED_AT" TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UPDATED_AT" TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    NOT CLUSTER PRIMARY KEY ("ID")
) STORAGE(ON "MAIN", CLUSTERBTR);

COMMENT ON TABLE "MINDMATE"."DECISION_SESSION" IS '决策会话';
COMMENT ON COLUMN "MINDMATE"."DECISION_SESSION"."ID" IS '会话ID';
COMMENT ON COLUMN "MINDMATE"."DECISION_SESSION"."USER_ID" IS '归属用户ID';
COMMENT ON COLUMN "MINDMATE"."DECISION_SESSION"."TITLE" IS '会话标题，应用限制100字符，预留UTF-8字节空间';
COMMENT ON COLUMN "MINDMATE"."DECISION_SESSION"."CREATED_AT" IS '创建时间';
COMMENT ON COLUMN "MINDMATE"."DECISION_SESSION"."UPDATED_AT" IS '最近成功消息更新时间';

CREATE INDEX "IDX_DEC_SESSION_OWNER_TIME" ON "MINDMATE"."DECISION_SESSION" ("USER_ID", "UPDATED_AT", "ID");

CREATE TABLE "MINDMATE"."DECISION_MESSAGE"
(
    "ID"         BIGINT IDENTITY(1, 1) NOT NULL,
    "SESSION_ID" BIGINT                              NOT NULL,
    "USER_ID"    BIGINT                              NOT NULL,
    "ROLE"       VARCHAR(16)                         NOT NULL,
    "CONTENT" CLOB NOT NULL,
    "CREATED_AT" TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    NOT CLUSTER PRIMARY KEY ("ID"),
    CONSTRAINT "CK_DEC_MESSAGE_ROLE" CHECK ("ROLE" IN ('user', 'assistant'))
) STORAGE(ON "MAIN", CLUSTERBTR);

COMMENT ON TABLE "MINDMATE"."DECISION_MESSAGE" IS '决策消息，仅在模型成功后同事务保存完整一轮';
COMMENT ON COLUMN "MINDMATE"."DECISION_MESSAGE"."ID" IS '消息ID，同会话按ID排序';
COMMENT ON COLUMN "MINDMATE"."DECISION_MESSAGE"."SESSION_ID" IS '所属会话ID，应用维护关联';
COMMENT ON COLUMN "MINDMATE"."DECISION_MESSAGE"."USER_ID" IS '归属用户ID，查询和删除均限定owner';
COMMENT ON COLUMN "MINDMATE"."DECISION_MESSAGE"."ROLE" IS '消息角色：user或assistant';
COMMENT ON COLUMN "MINDMATE"."DECISION_MESSAGE"."CONTENT" IS '消息正文，用户输入由应用限制4000字符';
COMMENT ON COLUMN "MINDMATE"."DECISION_MESSAGE"."CREATED_AT" IS '创建时间';

CREATE INDEX "IDX_DEC_MESSAGE_OWNER_SESSION" ON "MINDMATE"."DECISION_MESSAGE" ("USER_ID", "SESSION_ID", "ID");
